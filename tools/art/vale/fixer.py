def grid(text):
    rows = text.strip("\n").split("\n")
    for y, r in enumerate(rows):
        assert len(r) == FW, (y, len(r), r)
    assert len(rows) == FH, len(rows)
    return [list(r) for r in rows]


def copy(g):
    return [r[:] for r in g]


def patch(g, top, left, text):
    """Overlay a small grid: "." keeps what is there, "_" makes it transparent."""
    for y, r in enumerate(text.strip("\n").split("\n")):
        for x, ch in enumerate(r):
            if ch == ".":
                continue
            g[top + y][left + x] = "." if ch == "_" else ch
    return g


def lift(g, top, bottom, dy=-1):
    """Move rows top..bottom by dy (up when negative); the row left behind repeats its neighbour."""
    rows = [g[y][:] for y in range(top, bottom + 1)]
    out = copy(g)
    for i, r in enumerate(rows):
        out[top + i + dy] = r
    if dy < 0:
        for y in range(bottom + dy + 1, bottom + 1):
            out[y] = g[bottom + 1][:] if bottom + 1 < FH else ["."] * FW
    return out


def image(g):
    im = Image.new("RGBA", (FW, FH), (0, 0, 0, 0))
    for y, r in enumerate(g):
        for x, ch in enumerate(r):
            if ch != ".":
                h = PAL[ch].lstrip("#")
                im.putpixel((x, y), tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,))
    return im


