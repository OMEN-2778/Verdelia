# ================================================================ the portrait for talking to him
# A 48 x 48 bust, looking out at you, three-quarters lit from the top left. The shapes are laid in
# with a few ellipses and polygons, then the outline, the shading and every feature are put in by
# hand; each expression redraws his brows, eyes and mouth.
PW = PH = 48


def _shape(g, draw, ch, keep=None):
    from PIL import ImageDraw
    m = Image.new("L", (PW, PH), 0)
    draw(ImageDraw.Draw(m))
    for y in range(PH):
        for x in range(PW):
            if m.getpixel((x, y)) and (keep is None or g[y][x] in keep):
                g[y][x] = ch


def portrait_base():
    g = [["."] * PW for _ in range(PH)]
    # jacket and shirt
    _shape(g, lambda d: d.polygon([(2, 47), (5, 41), (12, 37), (36, 37), (43, 41), (46, 47)], fill=1), "O")
    _shape(g, lambda d: d.polygon([(17, 37), (31, 37), (27, 47), (21, 47)], fill=1), "N")
    _shape(g, lambda d: d.polygon([(12, 37), (18, 37), (22, 47), (17, 47), (13, 42)], fill=1), "R")  # lapel, lit
    _shape(g, lambda d: d.polygon([(30, 37), (36, 37), (35, 42), (31, 47), (27, 47)], fill=1), "r")  # lapel, shade
    # neck, ears, face
    _shape(g, lambda d: d.rectangle([19, 31, 29, 38], fill=1), "s")
    _shape(g, lambda d: d.ellipse([10, 20, 15, 28], fill=1), "S")
    _shape(g, lambda d: d.ellipse([33, 20, 38, 28], fill=1), "s")
    _shape(g, lambda d: d.polygon([(13, 18), (35, 18), (35, 27), (31, 33), (26, 36), (22, 36), (17, 33), (13, 27)], fill=1), "S")
    for y in range(PH):  # the shaded side of the face and jaw
        for x in range(PW):
            if g[y][x] == "S" and (x >= 31 or (y >= 32 and x >= 25)):
                g[y][x] = "s"
    # hair: the mass over the head, spikes, locks over the temples
    _shape(g, lambda d: d.ellipse([10, 3, 38, 26], fill=1), "H", keep=".")
    _shape(g, lambda d: d.ellipse([11, 4, 37, 17], fill=1), "H")
    for pts in [[(12, 10), (8, 3), (17, 7)], [(16, 6), (15, 0), (22, 5)], [(21, 5), (24, 0), (27, 5)],
                [(26, 5), (32, 1), (31, 7)], [(31, 7), (39, 3), (36, 11)], [(35, 11), (41, 9), (37, 16)],
                [(11, 13), (6, 10), (11, 18)]]:
        _shape(g, lambda d, p=pts: d.polygon(p, fill=1), "H")
    for pts in [[(11, 18), (13, 26), (15, 19)], [(37, 18), (35, 26), (33, 19)]]:
        _shape(g, lambda d, p=pts: d.polygon(p, fill=1), "h")
    for y in range(PH):  # light on the top left of the hair, shade on the right
        for x in range(PW):
            if g[y][x] == "H":
                if x + y < 22 or (x < 22 and y < 8):
                    g[y][x] = "L"
                elif x > 31 or y > 15:
                    g[y][x] = "h"
    # the goggles pushed up on his forehead: strap, frames, lenses
    _shape(g, lambda d: d.rectangle([10, 13, 38, 15], fill=1), "G")
    _shape(g, lambda d: d.rectangle([10, 15, 38, 15], fill=1), "g")
    for x0 in (13, 26):
        _shape(g, lambda d, a=x0: d.rounded_rectangle([a, 10, a + 8, 17], radius=2, fill=1), "g")
        _shape(g, lambda d, a=x0: d.rounded_rectangle([a + 1, 11, a + 7, 16], radius=2, fill=1), "Q")
        _shape(g, lambda d, a=x0: d.rectangle([a + 4, 14, a + 7, 16], fill=1), "q")
        g[12][x0 + 2] = g[12][x0 + 3] = g[13][x0 + 2] = "w"
    # the plaster across his left cheek
    _shape(g, lambda d: d.polygon([(28, 27), (31, 25), (33, 26), (30, 28)], fill=1), "Z")
    g[26][30] = "z"
    # the outline round everything
    out = [r[:] for r in g]
    for y in range(PH):
        for x in range(PW):
            if g[y][x] != ".":
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if 0 <= x + dx < PW and 0 <= y + dy < PH and g[y + dy][x + dx] != ".":
                    out[y][x] = "o"
                    break
    # a darker line where hair meets skin, and round the jacket opening
    for y in range(PH):
        for x in range(PW):
            if out[y][x] in "SsZ" and any(0 <= y + dy < PH and out[y + dy][x] in "Hhl" for dy in (-1,)):
                out[y][x] = "k"
    # the nose: a lit ridge and its shadow
    for y, x, c in ((25, 24, "s"), (26, 24, "s"), (27, 23, "k"), (27, 24, "k"), (26, 25, "S")):
        out[y][x] = c
    return out


